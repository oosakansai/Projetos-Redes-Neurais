# pip install -r bibliotecas.txt
import torch
import torch.nn as nn
import torch.optim as optim
from torchvision import datasets, transforms
from torch.utils.data import DataLoader, random_split
import matplotlib.pyplot as plt
import numpy as np
import random

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print(f"Dispositivo utilizado: {device}")

seed = 42
torch.manual_seed(seed)
np.random.seed(seed)
random.seed(seed)

class Encoder(nn.Module):
    def __init__(self, input_dim, hidden_dims, latent_dim):
        super(Encoder, self).__init__()
        layers = []
        prev_dim = input_dim
        for h_dim in hidden_dims:
            layers.append(nn.Linear(prev_dim, h_dim))
            layers.append(nn.ReLU())
            prev_dim = h_dim
        self.hidden = nn.Sequential(*layers)
        self.fc_mu = nn.Linear(prev_dim, latent_dim)
        self.fc_logvar = nn.Linear(prev_dim, latent_dim)

    def forward(self, x):
        h = self.hidden(x)
        mu = self.fc_mu(h)
        logvar = self.fc_logvar(h)
        return mu, logvar


class Decoder(nn.Module):
    def __init__(self, latent_dim, hidden_dims, output_dim):
        super(Decoder, self).__init__()
        layers = []
        prev_dim = latent_dim
        # caminho inverso das camadas ocultas
        for h_dim in reversed(hidden_dims):
            layers.append(nn.Linear(prev_dim, h_dim))
            layers.append(nn.ReLU())
            prev_dim = h_dim
        layers.append(nn.Linear(prev_dim, output_dim))
        layers.append(nn.Sigmoid())
        self.decoder = nn.Sequential(*layers)

    def forward(self, z):
        return self.decoder(z)


class VAE(nn.Module):
    def __init__(self, input_dim, hidden_dims, latent_dim):
        super(VAE, self).__init__()
        self.encoder = Encoder(input_dim, hidden_dims, latent_dim)
        self.decoder = Decoder(latent_dim, hidden_dims, input_dim)

    def forward(self, x):
        mu, logvar = self.encoder(x)
        std = torch.exp(0.5 * logvar)
        eps = torch.randn_like(std)
        z = mu + eps * std
        reconstrução_final = self.decoder(z)
        return reconstrução_final, mu, logvar

def loss_function(x, reconstrução_final, mu, logvar):
    BCE = nn.functional.binary_cross_entropy(reconstrução_final, x, reduction='sum') # entropia cruzada binária para erro de reconstrução
    KLD = -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp()) #divergência KL
    return BCE + KLD

# hiperparametros otimizados para espaço latente de 8 dimensões
input_dim = 784
hidden_dim = [64, 64]
latent_dim = 8
lr = 1e-2
batch_size = 400
epochs = 20

# carregar dados, dividir em treinemanto e validação
transform = transforms.Compose([transforms.ToTensor(), transforms.Lambda(lambda x: x.view(-1))]) #é necessário comprimir para uma única dimensão de 784 unidades (antes era em formato [60000, 28, 28])

full_train = datasets.FashionMNIST(root='./data', train=True, download=True, transform=transform)

train_size = int(0.8 * len(full_train))
validation_size = len(full_train) - train_size

train_dataset, validation_dataset = random_split(full_train, [train_size, validation_size])

train_loader = DataLoader(train_dataset, batch_size=batch_size, shuffle=True)
validation_loader   = DataLoader(validation_dataset, batch_size=batch_size, shuffle=False)

# declarar modelo
vae = VAE(input_dim, hidden_dim, latent_dim).to(device)
optimizer = optim.Adam(vae.parameters(), lr=lr)

train_loss_array= []
validation_loss_array = []
# calculo da perda média por imagem, não os conjuntos inteiros
for epoch in range(epochs):
    vae.train()
    train_loss = 0
    for x, _ in train_loader:
        x = x.to(device)
        optimizer.zero_grad()
        reconstrução_final, mu, logvar = vae(x)
        loss = loss_function(x, reconstrução_final, mu, logvar)
        loss.backward()
        train_loss += loss.item()
        optimizer.step()

    train_loss /= len(train_loader.dataset)
    train_loss_array.append(train_loss)

    vae.eval()
    validation_loss = 0
    with torch.no_grad():
        for x, _ in validation_loader:
            x = x.to(device)
            reconstrução_final, mu, logvar = vae(x)
            loss = loss_function(x, reconstrução_final, mu, logvar)
            validation_loss += loss.item()

    validation_loss /= len(validation_loader.dataset)
    validation_loss_array.append(validation_loss)

# Gráficos épocas X erro médio por imagem, para treinamento e validação
plt.figure(figsize=(8, 5))
epochs_range = range(1, epochs + 1)
plt.plot(epochs_range, train_loss_array, label='Treinamento', color='royalblue')
plt.plot(epochs_range, validation_loss_array, label='Validação', color='deeppink')
plt.xlabel('Época')
plt.ylabel('Erro Médio por Imagem')
plt.title('Erro de Treinamento vs Validação')
plt.legend()
plt.grid(True)
plt.show()

train_loss_formatted = [f"{loss:.4f}" for loss in train_loss_array]
validation_loss_formatted = [f"{loss:.4f}" for loss in validation_loss_array]

print(f'perda treinamento: {train_loss_formatted}')
print(f'perda validação: {validation_loss_formatted}')

from sklearn.decomposition import PCA
class_names = ["T-shirt/top", "Trouser", "Pullover", "Dress", "Coat",
               "Sandal", "Shirt", "Sneaker", "Bag", "Ankle boot"]

# 1. Carregar o conjunto de teste
test_dataset = datasets.FashionMNIST(root='./data', train=False, download=True, transform=transform)
test_loader = DataLoader(test_dataset, batch_size=batch_size, shuffle=False)

# 2. Extrair o espaço latente (mu) do teste
vae.eval()
latent_mus = []
labels = []

with torch.no_grad():
    for x, y in test_loader:
        x = x.to(device)
        mu, logvar = vae.encoder(x)
        latent_mus.append(mu.cpu())
        labels.append(y)

latent_mus = torch.cat(latent_mus).numpy()
labels = torch.cat(labels).numpy()

# 3. Projetar de 8D para 2D com PCA
pca = PCA(n_components=2)
latent_2d = pca.fit_transform(latent_mus)

print(f"Variância explicada pelo PCA: {pca.explained_variance_ratio_.sum():.2%}")

# 4. Plotar
plt.figure(figsize=(8, 6))
scatter = plt.scatter(
    latent_2d[:, 0],
    latent_2d[:, 1],
    c=labels,
    cmap='tab10',
    alpha=0.6,
    s=10
)
cbar = plt.colorbar(scatter, ticks=range(10))
cbar.ax.set_yticklabels(class_names)
plt.title("Projeção PCA do Espaço Latente 8D - Conjunto de Teste")
plt.xlabel("PC1")
plt.ylabel("PC2")
plt.show()

print(f"Variância explicada pelo PCA (2 componentes): {pca.explained_variance_ratio_.sum()*100:.2f}%")
print(f"Detalhamento: PC1 = {pca.explained_variance_ratio_[0]*100:.2f}% | PC2 = {pca.explained_variance_ratio_[1]*100:.2f}%")

# Manifold 2D do espaço latente
n = 15  # grade 15x15
digit_size = 28
figure = np.zeros((digit_size * n, digit_size * n))

grid_x = np.linspace(3, -3, n)
grid_y = np.linspace(-3, 3, n)

vae.eval()
with torch.no_grad():
    for i, yi in enumerate(grid_x):
        for j, xi in enumerate(grid_y):
            z_2d = np.array([[xi, yi]], dtype=np.float32)
            z_8d = pca.inverse_transform(z_2d)
            z_sample = torch.tensor(z_8d, dtype=torch.float32).to(device)

            x_decoded = vae.decoder(z_sample)
            digit = x_decoded[0].reshape(digit_size, digit_size).cpu().numpy()
            figure[i * digit_size: (i + 1) * digit_size,
                   j * digit_size: (j + 1) * digit_size] = digit

plt.figure(figsize=(10, 10))
plt.imshow(figure, cmap='gray')
plt.title("Manifold 2D do Espaço Latente (Projeção PCA Inversa)")
plt.axis('off')
plt.show()

