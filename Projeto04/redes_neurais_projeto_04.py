def create_sequences(data, tam_janela, k, t_start, t_end):
    x, y = [], []
    for t in range(max(t_start, tam_janela + k - 1), t_end):
        i = t - tam_janela - k + 1            # início da janela
        x.append(data[i : i + tam_janela, :]) # janela de tam_janela dias
        y.append(data[t, 3])                  # Close em t (= fim da janela + K)
    return np.array(x), np.array(y)

