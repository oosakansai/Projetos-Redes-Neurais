class LSTM(nn.Module):
    def __init__(self, input_size, hidden_size, num_layers, dropout=0.0):
        super().__init__()
        self.lstm = nn.LSTM(input_size, hidden_size, num_layers, batch_first=True,
                            dropout=dropout if num_layers > 1 else 0.0)
        self.drop = nn.Dropout(dropout)
        self.fc = nn.Linear(hidden_size, 1)

    def forward(self, x):
        out, _ = self.lstm(x)
        out = self.drop(out[:, -1, :])
        return self.fc(out)

input_size = 6
loss_fn = nn.MSELoss()

def train_model(hidden_size, num_layers, lr, epochs, momentum=0.0, l2=0.0, l1=0.0, dropout=0.0):

    model = LSTM(input_size, hidden_size, num_layers, dropout)
    optimizer = torch.optim.SGD(model.parameters(), lr=lr, momentum=momentum, weight_decay=l2)

    train_losses, val_losses = [], []
    train_maes, val_maes = [], []
    best_val, best_state = float('inf'), None

    for epoch in range(epochs):

        model.train()
        epoch_train_loss, epoch_train_mae = 0.0, 0.0
        for Xb, yb in train_loader:
            optimizer.zero_grad()
            pred = model(Xb)
            mse = loss_fn(pred, yb)
            loss = mse
            if l1 > 0:
                loss = mse + l1 * sum(p.abs().sum() for p in model.parameters())
            loss.backward()
            optimizer.step()
            epoch_train_loss += mse.item()
            epoch_train_mae += (pred - yb).abs().mean().item()
        train_losses.append(epoch_train_loss / len(train_loader))
        train_maes.append(epoch_train_mae / len(train_loader))


        model.eval()
        epoch_val_loss, epoch_val_mae = 0.0, 0.0
        with torch.no_grad():
            for Xb, yb in val_loader:
                pred = model(Xb)
                epoch_val_loss += loss_fn(pred, yb).item()
                epoch_val_mae += (pred - yb).abs().mean().item()
        avg_val = epoch_val_loss / len(val_loader)
        val_losses.append(avg_val)
        val_maes.append(epoch_val_mae / len(val_loader))

        if avg_val < best_val:
            best_val = avg_val
            best_state = {k_: v.clone() for k_, v in model.state_dict().items()}

    model.load_state_dict(best_state)
    return model, train_losses, val_losses, best_val, train_maes, val_maes

